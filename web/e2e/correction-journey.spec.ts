import { test, expect } from '@playwright/test';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { createHash, randomUUID } from 'node:crypto';
import { execFileSync } from 'node:child_process';

test('reviewed phone creates a separately approved candidate with complete correction evidence', async ({ page }, info) => {
  const inbox = mkdtempSync(join(process.env.PDTL_BROWSER_INPUTS!, 'correction-'));
  const source = `correction-roster-${info.project.name}-${Date.now()}`;
  const actor = { actor: 'Synthetic reviewer', reason: 'Reviewed synthetic phone correction' };
  const fields = ['record_id','npi','provider_name','address','city','state','zip','phone','location_id'];
  const data = Buffer.from(readFileSync(resolve('../tests/fixtures/managed_feed/baseline.csv'), 'utf8').split('\n').slice(0,3).join('\n') + '\n');
  async function post(url: string, body: unknown) { const r = await page.request.post(url, { data: body }); expect(r.ok(), await r.text()).toBe(true); return r.json(); }
  async function get(url: string) { const r = await page.request.get(url); expect(r.ok(), await r.text()).toBe(true); return r.json(); }
  const upload = await page.request.post(`/api/intakes/files?${new URLSearchParams({filename:'recipe.csv',source,dataset_scope:'weekly'})}`, {data,headers:{'Content-Type':'application/octet-stream'}});
  expect(upload.ok(), await upload.text()).toBe(true);
  const receipt = await upload.json();
  const proposal = await post(`/api/intakes/${receipt.id}/recipes`, {...actor,name:'Correction fixture recipe',expected_attempt:receipt.attempt_id,definition:{version:1,mapping:Object.fromEntries(fields.map(f => [f,f])),required:fields,transforms:{phone:['phone_us']}}});
  const recipe = await post(`/api/intakes/${receipt.id}/recipes/${proposal.id}/approve`, {...actor,expected_attempt:receipt.attempt_id});
  let feed = await post('/api/feeds', {...actor,name:`Correction fixture ${info.project.name}`,source,scope:'weekly',inbox,owner:'Synthetic owner',start_date:'2026-10-05'});
  const contract = await post(`/api/feeds/${feed.id}/contracts`, {...actor,definition:{recipe_revision_id:recipe.id,required_headers:fields}});
  const approved = await post(`/api/feeds/${feed.id}/contracts/${contract.id}/approve`, actor);
  feed = await post(`/api/feeds/${feed.id}/configure`, {...actor,expected_revision:feed.revision,config:{contract_id:approved.id,enabled:true}});
  writeFileSync(join(inbox,'base.csv'),data);
  writeFileSync(join(inbox,'base.manifest.json'),JSON.stringify({delivery_id:'base',period:'2026-10-05',as_of:'2026-10-05',snapshot:'full',filename:'base.csv',sha256:createHash('sha256').update(data).digest('hex')}));
  feed = await post(`/api/feeds/${feed.id}/tick`, {});
  const base = feed.versions[0].id;
  const baseDetail = await get(`/api/feed-versions/${base}`);
  await post(`/api/feed-versions/${base}/decide`, {...actor,expected_report:baseDetail.report_hash,expected_current:baseDetail.current_version,decision:'approved',idempotency_key:randomUUID()});
  const original = await (await page.request.get(`/api/feed-versions/${base}/export`)).text();
  const records = [{record_id:'SYNTHETIC-001',npi:'1234567890',provider_name:'Synthetic Avery Clinic',address:'10 Fiction Street',city:'Example',state:'MA',zip:'02108',phone:'6175550199',phone_extension:'0042',location_id:'NORTH',entity_type:'clinician'}, {record_id:'SYNTHETIC-001',npi:'1234567890',provider_name:'Synthetic Avery Clinic',address:'20 Fiction Street',city:'Example',state:'MA',zip:'02109',phone:'6175550102',location_id:'SOUTH',entity_type:'clinician'}];
  const refResponse = await page.request.post(`/api/intakes/files?${new URLSearchParams({filename:'reference.json',source:'synthetic-correction-reference',designation:'synthetic',profile:'flat'})}`, {data:Buffer.from(JSON.stringify(records)),headers:{'Content-Type':'application/octet-stream'}});
  expect(refResponse.ok(), await refResponse.text()).toBe(true);
  const ref = await refResponse.json();
  const run = await post('/api/reconciliation/runs', {...actor,inputs:[{receipt_id:baseDetail.manifest.receipt_id,attempt_id:baseDetail.manifest.attempt_id,entity_kind:'clinician'},{receipt_id:ref.id,attempt_id:ref.attempt_id,entity_kind:'clinician'}]});
  const candidates = (await get(`/api/reconciliation/runs/${run.id}/candidates?limit=100`)).items;
  let person = '', north = '';
  for (const kind of ['clinician','location']) for (const candidate of candidates.filter((c: {kind:string}) => c.kind === kind)) {
    const left = candidate.left_record.comparison.address.line1, right = candidate.right_record.comparison.address.line1;
    if (left !== right || (kind === 'location' && !left.startsWith('10 '))) continue;
    const current = await get(`/api/reconciliation/runs/${run.id}/candidates/${candidate.id}/review`);
    const result = await post('/api/reconciliation/links', {...actor,run_id:run.id,candidate_id:candidate.id,decision:'approve',request_id:randomUUID(),expected_snapshot:current.review_snapshot,expected_revisions:Object.fromEntries(Object.entries(current.current_links).map(([key,value]) => [key,(value as {id:string}|null)?.id ?? null])),expected_decision:current.latest_decision?.id ?? null,...(kind === 'clinician' && person ? {target_id:person} : {new_label:kind === 'location' ? 'NORTH' : 'Avery'})});
    if (kind === 'clinician') person = result.decision.target_id; else north = result.decision.target_id;
  }
  expect(person && north).toBeTruthy();
  const context = await get(`/api/reconciliation/fields/${person}?location_id=${north}`);
  const phone = context.fields.find((f:{field:string}) => f.field === 'phone');
  const selected = phone.options.find((o:{source:string}) => o.source === 'synthetic-correction-reference');
  await post('/api/reconciliation/field-decisions', {...actor,clinician_id:person,location_id:north,field:'phone',decision:'select',selected_ref:selected.ref,expected_snapshot:context.snapshot,expected_decision:phone.decision?.id ?? null,request_id:randomUUID()});
  await page.goto(`/?view=feeds&feed=${feed.id}&version=${base}`);
  await expect(page.getByRole('heading',{name:'Dataset review · approved'})).toBeVisible();
  await page.getByText('Decision attribution for additional actions').click();
  await page.getByLabel('Reviewer',{exact:true}).fill(actor.actor);
  await page.getByLabel('Decision reason',{exact:true}).fill(actor.reason);
  await page.getByRole('button',{name:'Inspect reviewed phone decisions'}).click();
  const selector = page.getByLabel('Reviewed office and clinician');
  await expect(selector.locator('option')).toHaveCount(2);
  await selector.selectOption({label:'Avery · NORTH'});
  await expect(page.getByText(/6175550199 · extension: 0042/)).toBeVisible();
  await page.screenshot({path:info.outputPath('correction-choice.png'),fullPage:true});
  await page.getByRole('button',{name:'Create roster candidate'}).click();
  await expect(page.getByRole('heading',{name:'Dataset review · candidate'})).toBeVisible();
  expect((await get(`/api/feeds/${feed.id}/current`)).version_id).toBe(base);
  const candidate = new URL(page.url()).searchParams.get('version')!;
  expect(candidate).not.toBe(base);
  const qualityDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download complete quality report JSON' }).click();
  const quality = JSON.parse(readFileSync((await (await qualityDownload).path())!, 'utf8'));
  expect(quality).toMatchObject({version_id: candidate, feed_id: feed.id, state: 'candidate', notice: 'Review evidence only; not an approved dataset export'});
  expect(quality.report.counts.valid).toBe(2);
  expect(quality).not.toHaveProperty('records');
  expect((await get(`/api/feeds/${feed.id}/current`)).version_id).toBe(base);
  await page.getByRole('button',{name:'Approve dataset version'}).click();
  await expect(page.getByRole('heading',{name:'Dataset review · approved'})).toBeVisible();
  expect((await get(`/api/feeds/${feed.id}/current`)).version_id).toBe(candidate);
  expect(await (await page.request.get(`/api/feed-versions/${base}/export`)).text()).toBe(original);
  await page.getByRole('button',{name:'Preview approved workbook'}).click();
  await expect(page.getByRole('region',{name:'Reviewed export corrections'})).toContainText('6175550199');
  await page.getByText('Inspect directory sample (2 rows)').click();
  await page.screenshot({path:info.outputPath('approved-correction-preview.png'),fullPage:true});
  const jsonDownload = page.waitForEvent('download'); await page.getByRole('button',{name:'Download reviewed data JSON'}).click();
  const json = JSON.parse(readFileSync((await (await jsonDownload).path())!, 'utf8'));
  expect(json.directory).toHaveLength(2);
  expect(json.directory.find((r:{location_id:string}) => r.location_id === 'NORTH')).toMatchObject({phone:'6175550199',phone_extension:'0042'});
  expect(json.directory.find((r:{location_id:string}) => r.location_id === 'SOUTH').phone).toBe('6175550102');
  expect(json.corrections).toHaveLength(1);
  const xlsxDownload = page.waitForEvent('download'); await page.getByRole('button',{name:'Download reviewed workbook XLSX'}).click();
  const path = info.outputPath('approved-correction.xlsx');
  await (await xlsxDownload).saveAs(path);
  const workbook = JSON.parse(execFileSync('python3',['-c',"import json,sys; from openpyxl import load_workbook; w=load_workbook(sys.argv[1],read_only=True,data_only=True); print(json.dumps({s:list(w[s].values) for s in w.sheetnames},default=str))",path!],{encoding:'utf8'}));
  expect(workbook['Reviewed corrections']).toBeTruthy();
  expect(JSON.stringify(workbook['Reviewed corrections'])).toContain('6175550199');
  expect(JSON.stringify(workbook['Reviewed corrections'])).toContain('0042');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);

  // A later source delivery repeats the original phone. Source-to-source is
  // unchanged, but the approved effective roster contains the local correction.
  writeFileSync(join(inbox, 'later.csv'), data);
  writeFileSync(join(inbox, 'later.manifest.json'), JSON.stringify({delivery_id:'later',period:'2026-10-12',as_of:'2026-10-12',snapshot:'full',filename:'later.csv',sha256:createHash('sha256').update(data).digest('hex')}));
  const laterFeed = await post(`/api/feeds/${feed.id}/tick`, {});
  const laterId = laterFeed.versions.find((item:{period:string}) => item.period === '2026-10-12').id;
  expect(laterId).not.toBe(candidate);
  await page.goto(`/?view=feeds&feed=${feed.id}&version=${laterId}`);
  await expect(page.getByRole('heading',{name:'Dataset review · candidate'})).toBeVisible();
  const effective = page.getByRole('region',{name:'Effective corrected roster comparison'});
  await expect(effective).toContainText('6175550199 · extension: 0042');
  await expect(effective).toContainText('6175550101 · extension: Not supplied');
  await expect(effective).toContainText('Changed');
  const sourceComparison = page.getByRole('region',{name:'Delivery comparison',exact:true});
  await expect(sourceComparison).toContainText('Unchanged keys');
  await expect(sourceComparison.getByText('Unchanged keys',{exact:true}).locator('..')).toContainText('2');
  await expect(page.getByRole('button',{name:'Approve dataset version'})).toBeDisabled();
  expect((await get(`/api/feeds/${feed.id}/current`)).version_id).toBe(candidate);
  await page.getByLabel('Reviewer',{exact:true}).fill(actor.actor);
  await page.getByLabel('Decision reason',{exact:true}).fill('Reviewed source difference against approved correction');
  await page.screenshot({path:info.outputPath('effective-drift.png'),fullPage:true});
  await page.getByRole('button',{name:'Acknowledge effective_correction_drift'}).click();
  expect((await get(`/api/feeds/${feed.id}/current`)).version_id).toBe(candidate);
  await expect(page.getByRole('button',{name:'Approve dataset version'})).toBeEnabled();
  await page.getByRole('button',{name:'Approve dataset version'}).click();
  await expect(page.getByRole('heading',{name:'Dataset review · approved'})).toBeVisible();
  expect((await get(`/api/feeds/${feed.id}/current`)).version_id).toBe(laterId);
});
