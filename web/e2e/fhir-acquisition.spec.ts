import { expect, test } from '@playwright/test';
import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';

test('controlled HTTP capture keeps original pages, separate native acceptance and restart selection', async ({ page }, info) => {
  await page.goto('/?view=sources');
  const panel = page.getByRole('region', { name: 'Bounded FHIR captures', exact: true });
  await expect(panel.getByText('synthetic-browser', { exact: true })).toBeVisible();
  // Independent scenarios share one owned source. Respect a preceding scenario's
  // real persisted cooldown rather than resetting history or bypassing the worker.
  await expect.poll(async()=> (await (await page.request.get('/api/fhir-acquisitions')).json()).source.next_request_at,{timeout:6000}).toBeNull();
  await panel.getByRole('button',{name:'Refresh captures',exact:true}).click();
  await expect(panel.getByRole('button',{name:'Refresh captures',exact:true})).toBeEnabled();
  await panel.getByLabel('Capture operator', { exact: true }).fill('Synthetic network analyst');
  await panel.getByLabel('Capture reason', { exact: true }).fill('Review a bounded two-page query');
  await panel.getByRole('button', { name: 'Queue bounded capture', exact: true }).click();
  const capture = panel.getByRole('article', { name: 'Selected FHIR capture' });
  await expect(capture.getByText('queued', { exact: true })).toBeVisible();
  await expect(capture.getByText('0 pages · 0 references · 0 requests · 0 retained bytes', { exact: true })).toBeVisible();
  const captureId = new URL(page.url()).searchParams.get('acquisition')!;
  for (const pages of [1, 2]) {
    await panel.getByRole('button', { name: 'Run one capture step', exact: true }).click();
    await expect(capture.getByText(new RegExp(`^${pages} pages · 0 references · ${pages} requests`))).toBeVisible();
    await expect(panel.getByRole('button', { name: 'Run one capture step', exact: true })).toBeEnabled();
  }
  await panel.getByRole('button', { name: 'Run one capture step', exact: true }).click();
  await expect(capture.getByText('complete', { exact: true })).toBeVisible();
  const detail = await (await page.request.get(`/api/fhir-acquisitions/${captureId}`)).json();
  expect(detail.checkpoint.requests).toBe(2);
  await capture.getByText('Capture history and original responses', { exact: true }).click();
  const response = detail.events.find((event: any) => event.kind === 'response');
  await capture.getByText(new RegExp(`^response · .* · Event ${response.seq}$`)).click();
  const pending = page.waitForEvent('download');
  await capture.getByRole('link', { name: `Download original response ${response.seq}`, exact: true }).click();
  const rawPath = info.outputPath('original-response.json');
  await (await pending).saveAs(rawPath);
  const raw = await readFile(rawPath);
  expect(createHash('sha256').update(raw).digest('hex')).toBe(response.artifact_sha);
  expect(JSON.parse(raw.toString()).entry).toHaveLength(3);
  await page.reload();
  await expect(panel.getByRole('article', { name: 'Selected FHIR capture' }).getByText('complete', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('capture-complete.png'), fullPage: true });
  await panel.getByRole('link', { name: 'Review captured reference evidence', exact: true }).click();
  const native = page.getByRole('region', { name: 'Native FHIR evidence', exact: true });
  await expect(native.getByText('preview ready', { exact: true })).toBeVisible();
  await expect(native.getByRole('link', { name: 'Download assembled searchset', exact: true })).toBeVisible();
  await expect(native.getByRole('link', { name: 'Download original', exact: true })).toHaveCount(0);
  const packet = await (await page.request.get(`/api/intakes/${detail.receipt_id}/packet`)).json();
  expect(packet.observations).toEqual([]);
  expect(packet.cases).toEqual([]);
  await native.getByLabel('Reference reviewer', { exact: true }).fill('Synthetic reference reviewer');
  await native.getByLabel('Reference review reason', { exact: true }).fill('Review source coverage separately');
  await native.getByRole('button', { name: 'Accept reference resources', exact: true }).click();
  await expect(native.getByText(/^(committed|duplicate delivery)$/)).toBeVisible();
  const accepted = await (await page.request.get(`/api/intakes/${detail.receipt_id}/packet`)).json();
  expect(accepted.observations.length).toBeGreaterThan(0);
});

test('429 capture retains its error body, waits without extra requests and supports cancellation', async ({ page }, info) => {
  await page.goto('/?view=sources');
  const panel = page.getByRole('region', { name: 'Bounded FHIR captures', exact: true });
  await expect(panel.getByText('synthetic-browser', { exact: true })).toBeVisible();
  await panel.getByLabel('Capture operator', { exact: true }).fill('Synthetic throttle analyst');
  await panel.getByLabel('Capture reason', { exact: true }).fill('Retain throttle and cancel safely');
  await panel.getByRole('combobox', { name: 'Capture resource', exact: true }).selectOption('PractitionerRole');
  await panel.getByRole('button', { name: 'Queue bounded capture', exact: true }).click();
  const capture = panel.getByRole('article', { name: 'Selected FHIR capture' });
  await panel.getByRole('button', { name: 'Run one capture step', exact: true }).click();
  await expect(capture.getByText('retry wait', { exact: true })).toBeVisible();
  await expect(capture.getByText('Source result: HTTP 429', { exact: true })).toBeVisible();
  await expect(panel.getByRole('button', { name: 'Run one capture step', exact: true })).toBeDisabled();
  const id = new URL(page.url()).searchParams.get('acquisition')!;
  await panel.getByRole('button', { name: 'Refresh captures', exact: true }).click();
  await expect(panel.getByRole('button', { name: 'Refresh captures', exact: true })).toBeEnabled();
  expect((await (await page.request.get(`/api/fhir-acquisitions/${id}`)).json()).checkpoint.requests).toBe(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('capture-throttle.png'), fullPage: true });
  await panel.getByRole('button', { name: 'Cancel capture', exact: true }).click();
  await expect(capture.getByText('cancelled', { exact: true })).toBeVisible();
  await page.reload();
  await expect(panel.getByText('cancelled', { exact: true })).toBeVisible();
  await expect(panel.getByRole('link', { name: 'Review captured reference evidence', exact: true })).toHaveCount(0);
});

test('source-native ID scopes a one-resource capture while acceptance remains separate',async({page},info)=>{
  await page.goto('/?view=sources');
  const panel=page.getByRole('region',{name:'Bounded FHIR captures',exact:true});
  await expect(panel.getByText('synthetic-browser',{exact:true})).toBeVisible();
  await expect.poll(async()=>(await(await page.request.get('/api/fhir-acquisitions')).json()).source.next_request_at,{timeout:6000}).toBeNull();
  await panel.getByRole('button',{name:'Refresh captures',exact:true}).click();
  await expect(panel.getByRole('button',{name:'Refresh captures',exact:true})).toBeEnabled();
  await panel.getByLabel('Capture operator',{exact:true}).fill('Synthetic ID analyst');
  await panel.getByLabel('Capture reason',{exact:true}).fill('Inspect one source-native office');
  await panel.getByLabel('Source-native resource ID (optional)',{exact:true}).fill('../Patient/x');
  await expect(panel.getByRole('button',{name:'Queue bounded capture',exact:true})).toBeDisabled();
  await panel.getByLabel('Source-native resource ID (optional)',{exact:true}).fill('north');
  await panel.getByRole('button',{name:'Queue bounded capture',exact:true}).click();
  const capture=panel.getByRole('article',{name:'Selected FHIR capture',exact:true});
  await expect(capture.getByText('Source resource ID:',{exact:false})).toHaveText('Source resource ID: north');
  const id=new URL(page.url()).searchParams.get('acquisition')!;
  await panel.getByRole('button',{name:'Run one capture step',exact:true}).click();
  await expect(capture.getByText(/^1 pages · 0 references · 1 requests/)).toBeVisible();
  await panel.getByRole('button',{name:'Run one capture step',exact:true}).click();
  await expect(capture.getByText('complete',{exact:true})).toBeVisible();
  const detail=await(await page.request.get(`/api/fhir-acquisitions/${id}`)).json();
  expect(detail.config.resource_id).toBe('north');expect(detail.checkpoint.requests).toBe(1);
  expect(detail.checkpoint.bodies[0].url).toMatch(/\/Location\/\?_count=1&_id=north$/);
  const packet=await(await page.request.get(`/api/intakes/${detail.receipt_id}/packet`)).json();
  expect(packet.metadata.query.resource_id).toBe('north');expect(packet.observations).toEqual([]);
  expect(packet.metadata.query_validation).toMatchObject({version:1,matched_entries:1,implicit_match_entries:1,included_entries:0,outcome_entries:0});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:info.outputPath('capture-filtered.png'),fullPage:true});
  await page.reload();await expect(capture.getByText('Source resource ID:',{exact:false})).toHaveText('Source resource ID: north');
  await panel.getByRole('link',{name:'Review captured reference evidence',exact:true}).click();
  const native=page.getByRole('region',{name:'Native FHIR evidence',exact:true});
  await expect(native.getByRole('region',{name:'Source query scope',exact:true})).toHaveText(/Checked matches: 1/);
  await native.getByLabel('Reference reviewer',{exact:true}).fill('Synthetic ID reviewer');
  await native.getByLabel('Reference review reason',{exact:true}).fill('Explicit review of the one-source office');
  await native.getByRole('button',{name:'Accept reference resources',exact:true}).click();
  await expect(native.getByText(/^(committed|duplicate delivery)$/)).toBeVisible();
  const accepted=await(await page.request.get(`/api/intakes/${detail.receipt_id}/packet`)).json();
  expect(accepted.observations).toHaveLength(1);expect(accepted.cases).toEqual([]);
});

test('HTTP success ignoring the native ID stays failed with exact raw evidence and no acceptance path',async({page},info)=>{
  await page.goto('/?view=sources');
  const panel=page.getByRole('region',{name:'Bounded FHIR captures',exact:true});
  await expect(panel.getByText('synthetic-browser',{exact:true})).toBeVisible();
  await expect.poll(async()=>(await(await page.request.get('/api/fhir-acquisitions')).json()).source.next_request_at,{timeout:6000}).toBeNull();
  await panel.getByRole('button',{name:'Refresh captures',exact:true}).click();
  await expect(panel.getByRole('button',{name:'Refresh captures',exact:true})).toBeEnabled();
  await panel.getByLabel('Capture operator',{exact:true}).fill('Synthetic scope analyst');
  await panel.getByLabel('Capture reason',{exact:true}).fill('Retain an ignored ID filter without publishing reference evidence');
  await panel.getByLabel('Source-native resource ID (optional)',{exact:true}).fill('ignored-filter');
  await panel.getByRole('button',{name:'Queue bounded capture',exact:true}).click();
  const capture=panel.getByRole('article',{name:'Selected FHIR capture',exact:true});
  await panel.getByRole('button',{name:'Run one capture step',exact:true}).click();
  await expect(capture.getByText('failed',{exact:true})).toBeVisible();
  await expect(capture.getByText(/Filtered query match.*differs from requested Location\/ignored-filter/)).toBeVisible();
  await expect(panel.getByRole('link',{name:'Review captured reference evidence',exact:true})).toHaveCount(0);
  const id=new URL(page.url()).searchParams.get('acquisition')!;
  const detail=await(await page.request.get(`/api/fhir-acquisitions/${id}`)).json();
  expect(detail.receipt_id).toBeNull();expect(detail.checkpoint.requests).toBe(1);
  const response=detail.events.find((event:any)=>event.kind==='response');
  expect(response.payload.status).toBe(200);
  await capture.getByText('Capture history and original responses',{exact:true}).click();
  await capture.getByText(new RegExp(`^response · .* · Event ${response.seq}$`)).click();
  const pending=page.waitForEvent('download');
  await capture.getByRole('link',{name:`Download original response ${response.seq}`,exact:true}).click();
  const rawPath=info.outputPath('ignored-filter-response.json');await(await pending).saveAs(rawPath);
  const raw=await readFile(rawPath);
  expect(createHash('sha256').update(raw).digest('hex')).toBe(response.artifact_sha);
  expect(JSON.parse(raw.toString()).entry[0].resource.id).toBe('north');
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:info.outputPath('ignored-filter-failed.png'),fullPage:true});
  await page.reload();await expect(capture.getByText('failed',{exact:true})).toBeVisible();
});
