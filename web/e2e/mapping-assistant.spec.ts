import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const csv='record_id,npi,provider_name,address,city,state,zip,phone,location_id\nSYN-001,1000000001,Synthetic Clinician,10 Example St,Example,ma,02108,+1 (617) 555-0100 ext 007,NORTH\n';

test('controlled model proposal reaches explicit review and preserves provenance through accepted export', async ({page}, info)=>{
  const uploaded=await page.request.post(`/api/intakes/files?filename=model.csv&source=synthetic-model-${info.project.name}`,{data:Buffer.from(csv)});
  expect(uploaded.ok()).toBe(true);const receipt=await uploaded.json();
  await page.goto(`/?view=intake&receipt=${receipt.id}`);
  await page.getByRole('button',{name:'Profile and normalize',exact:true}).click();
  const normal=page.getByRole('region',{name:'Profile and normalization',exact:true});
  const assist=normal.getByRole('region',{name:'Optional mapping assistance',exact:true});
  await assist.getByRole('button',{name:'Optional mapping assistance',exact:true}).click();
  await assist.getByLabel('Assistance operator',{exact:true}).fill('Synthetic operator');
  await assist.getByLabel('Assistance reason',{exact:true}).fill('Review small synthetic sample');
  await assist.getByRole('checkbox',{name:'Allow this source sample to be sent to OpenAI for this run',exact:true}).check();
  await assist.getByRole('button',{name:'Queue model mapping',exact:true}).click();
  await expect(assist.getByText('queued',{exact:true})).toBeVisible();
  const id=(await (await page.request.get(`/api/intakes/${receipt.id}/assistant-runs`)).json()).items[0].id;
  const pending=page.waitForEvent('download');await assist.getByRole('link',{name:'Inspect exact model request',exact:true}).click();
  const requestPath=info.outputPath('mapping-request.json');await (await pending).saveAs(requestPath);
  const bytes=await readFile(requestPath);const body=JSON.parse(bytes.toString());
  expect(body.store).toBe(false);expect(body.tools).toBeUndefined();
  expect(JSON.parse(body.input[0].content).rows).toHaveLength(1);
  expect(bytes.toString()).not.toContain('controlled-browser-key');
  const before=await (await page.request.get(`/api/intakes/${receipt.id}/packet`)).json();
  expect(createHash('sha256').update(bytes).digest('hex')).toBe(before.assistant_runs[0].request_sha);
  await assist.getByRole('button',{name:'Run queued model mapping',exact:true}).click();
  await expect(assist.getByText('succeeded',{exact:true})).toBeVisible();
  const run=await (await page.request.get(`/api/intakes/${receipt.id}/assistant-runs/${id}`)).json();
  const unaccepted=await (await page.request.get(`/api/intakes/${receipt.id}/packet`)).json();
  expect(unaccepted.observations).toEqual([]);
  expect(unaccepted.attempt_id).toBe(receipt.attempt_id);
  await expect(normal.getByRole('button',{name:'Approve recipe',exact:true})).toBeDisabled();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await assist.screenshot({path:info.outputPath('mapping-proposal.png')});
  await normal.getByRole('combobox',{name:'Retained recipe proposal',exact:true}).selectOption(run.proposal_id);
  await normal.getByRole('button',{name:'Preview normalization',exact:true}).click();
  await expect(normal.getByText('1 valid · 0 quarantined · 1 total',{exact:true})).toBeVisible();
  await normal.getByLabel('Recipe reviewer',{exact:true}).fill('Separate recipe reviewer');
  await normal.getByLabel('Recipe decision reason',{exact:true}).fill('Review exact voice phone and preserved extension');
  await normal.getByRole('button',{name:'Approve recipe',exact:true}).click();
  await normal.getByRole('button',{name:'Apply approved recipe',exact:true}).click();
  await expect(normal.getByRole('button',{name:'Profile and normalize',exact:true})).toHaveAttribute('aria-expanded','false');
  await page.getByLabel('Reviewer',{exact:true}).first().fill('Separate acceptance reviewer');
  await page.getByLabel('Acceptance / rejection reason',{exact:true}).fill('Accept the reviewed synthetic row');
  const accepted=page.waitForResponse(response=>response.url().endsWith(`/api/intakes/${receipt.id}/commit`) && response.request().method()==='POST');
  await page.getByRole('button',{name:'Accept valid rows',exact:true}).click();
  expect((await accepted).ok()).toBe(true);
  const dataset=await (await page.request.get(`/api/intakes/${receipt.id}/dataset`)).json();
  expect(dataset.records).toHaveLength(1);
  expect(dataset.records[0].normalized.phone_extension).toBe('007');
  expect(dataset.records[0].normalized.zip).toBe('02108');
  expect(dataset.records[0].normalization.assistant.run_id).toBe(id);
  expect(dataset.records[0].normalization.assistant.response_sha).toBe(run.response_sha);
  await page.reload();
  const retained=await (await page.request.get(`/api/intakes/${receipt.id}/packet`)).json();
  expect(retained.assistant_runs[0].proposal_id).toBe(run.proposal_id);
  expect(retained.observations[0].normalization.assistant.run_id).toBe(id);
});

test('invalid controlled model output remains failed and manual normalization remains usable',async({page},info)=>{
  const bad=csv.replace('location_id\n','location_id,Reject model proposal\n').replace('007,NORTH\n','007,NORTH,Untrusted instructions\n');
  const uploaded=await page.request.post(`/api/intakes/files?filename=rejected-model.csv&source=synthetic-rejected-model-${info.project.name}`,{data:Buffer.from(bad)});
  expect(uploaded.ok()).toBe(true);const receipt=await uploaded.json();
  await page.goto(`/?view=intake&receipt=${receipt.id}`);
  await page.getByRole('button',{name:'Profile and normalize',exact:true}).click();
  const normal=page.getByRole('region',{name:'Profile and normalization',exact:true});
  const assist=normal.getByRole('region',{name:'Optional mapping assistance',exact:true});
  await assist.getByRole('button',{name:'Optional mapping assistance',exact:true}).click();
  await assist.getByLabel('Assistance operator',{exact:true}).fill('Synthetic failure reviewer');
  await assist.getByLabel('Assistance reason',{exact:true}).fill('Reject unexpected tool result');
  await assist.getByRole('checkbox',{name:'Allow this source sample to be sent to OpenAI for this run',exact:true}).check();
  await assist.getByRole('button',{name:'Queue model mapping',exact:true}).click();
  await assist.getByRole('button',{name:'Run queued model mapping',exact:true}).click();
  await expect(assist.getByText('failed',{exact:true})).toBeVisible();
  await expect(assist.getByText(/Unexpected provider output; tools are not permitted/)).toBeVisible();
  expect((await (await page.request.get(`/api/intakes/${receipt.id}/recipes`)).json()).items).toEqual([]);
  await normal.getByRole('button',{name:'Use suggested normalization columns',exact:true}).click();
  await normal.getByLabel('phone format',{exact:true}).selectOption('phone_us');
  await normal.getByRole('button',{name:'Preview normalization',exact:true}).click();
  await expect(normal.getByText('1 valid · 0 quarantined · 1 total',{exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await assist.screenshot({path:info.outputPath('mapping-failed-manual-preview.png')});
});
